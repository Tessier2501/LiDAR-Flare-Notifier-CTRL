#!/usr/bin/env python3

import argparse
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

TOOL = "ptgl_replay"
SCRIPT_DIR = Path(__file__).resolve().parent


def wsl_path(path: Path) -> str:
    resolved = path.resolve()
    if not resolved.drive:
        raise SystemExit(f"not a Windows path: {resolved}")
    return f"/mnt/{resolved.drive[0].lower()}{resolved.as_posix()[2:]}"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog=TOOL,
        description="Parse a PTGL-100 frame stream with the firmware parser and print the results.",
    )
    parser.add_argument("--bin", required=True, help="frame stream file generated by ptgl_sim")
    parser.add_argument("--fps", default="100", help="frame rate used for the time column (default: 100)")
    parser.add_argument("--frames", action="store_true", help="print per-frame results")
    parser.add_argument("--expect", help="optional expected parser-accepted frame text file for comparisons")
    parser.add_argument("--distro", default="Ubuntu", help="WSL distribution name (default: Ubuntu)")
    args = parser.parse_args(argv)

    if shutil.which("wsl") is None:
        raise SystemExit("wsl not found; this tool needs Windows with WSL installed")

    firmware = SCRIPT_DIR.parents[2] / "LiDAR-Flare-Notifier-CTRL"
    sensor = firmware / "App" / "sensor"
    build_dir = SCRIPT_DIR.parents[1] / "temp" / TOOL
    sources = [sensor / "ptgl_parser.c", SCRIPT_DIR / "replay_view.c"]

    missing = [str(path) for path in sources if not path.is_file()]
    if missing:
        raise SystemExit("missing sources: " + ", ".join(missing))

    bin_path = Path(args.bin).resolve()
    if not bin_path.is_file():
        raise SystemExit(f"missing frame stream: {bin_path}")

    expect_path = None
    if args.expect:
        expect_path = Path(args.expect).resolve()
        if not expect_path.is_file():
            raise SystemExit(f"missing expectation file: {expect_path}")

    build_dir.mkdir(parents=True, exist_ok=True)
    binary = build_dir / "replay_view"
    include = shlex.quote(wsl_path(sensor))
    quoted_sources = " ".join(shlex.quote(wsl_path(path)) for path in sources)
    quoted_args = [shlex.quote(wsl_path(bin_path)), "--fps", shlex.quote(args.fps)]
    if args.frames:
        quoted_args.append("--frames")
    if expect_path is not None:
        quoted_args.extend(["--expect", shlex.quote(wsl_path(expect_path))])

    command = " ".join(
        [
            "gcc -std=c11 -Wall -Wextra -Werror",
            f"-I{include}",
            quoted_sources,
            "-o",
            shlex.quote(wsl_path(binary)),
            "&&",
            shlex.quote(wsl_path(binary)),
            *quoted_args,
        ]
    )
    result = subprocess.run(
        ["wsl", "-d", args.distro, "--", "bash", "-lc", command],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    print(f"stage=run exit={result.returncode}")
    for stream in (result.stdout, result.stderr):
        if stream:
            print(stream, end="" if stream.endswith("\n") else "\n")
    return result.returncode


if __name__ == "__main__":
    sys.exit(main())
